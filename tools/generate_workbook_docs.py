"""Generate docs/workbook-format.md from the importer schema and the model declarations.

uv run python tools/generate_workbook_docs.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from multifat.cli.run import PARAM_KEYS  # noqa: E402
from multifat.imp.schema import (  # noqa: E402
    DATASET_OPTIONAL,
    DATASET_REQUIRED,
    tokens_text,
    SUMMARY_CONSTANTS,
    SUMMARY_FIELDS,
)
from multifat.models.registry import param_table  # noqa: E402

OUT = ROOT / "docs/workbook-format.md"

# Workbook header (Summary) -> parameter name used by the models.
SUMMARY_PARAM = {v: k for k, v in PARAM_KEYS.items()}
SUMMARY_PARAM.update({"Tensile_fatigue_R0_MPa": "Sig0", "Torsional_fatigue_R0_MPa": "Tau0"})


def render() -> str:
    out = [
        "# Workbook format",
        "",
        "<!-- Generated by tools/generate_workbook_docs.py; do not edit by hand. -->",
        "",
        "One `.xlsx` file per material in `Experimental_Data/` (subfolders such as `archive/` are not",
        "read). The material ID is the file name without extension and without an ordering prefix",
        "such as `6_` (`6_42CrMo4_QT.xlsx` is `42CrMo4_QT`); two files with the same ID are rejected.",
        "`multifat-pipeline <workbook>` validates it, calibrates missing constants, runs every",
        "registered model and compares the results. Workbooks are never modified.",
        "",
        "## Summary sheet",
        "",
        "One header row; material values are read from the row whose cell reads `Average` (or the",
        "row given by a defined name `Average`). Only the Young's modulus and Poisson's ratio",
        "columns are required to load the workbook; every other value is required only by the",
        "models that use it (see the parameter table). A missing value can be left empty or written",
        "`Null`. Without E or nu the strains are undefined: only models whose value needs no strain",
        "run, the others are reported as skipped. A Summary in the revised format (a `Stress ratio R`",
        "column) is also checked for source rows naming another alloy than the file and for a",
        "tensile fatigue limit averaged over different stress ratios, which is then not used.",
        "",
        "| Parameter | Header contains | Required at load |",
        "|---|---|---|",
    ]
    for key, (header, required) in SUMMARY_FIELDS.items():
        out.append(
            f"| `{SUMMARY_PARAM.get(key, key)}` | {header} | {'yes' if required else 'no'} |"
        )
    out += [
        "",
        "Optional constants are matched on the whole header (case-insensitive; a trailing units",
        "group such as `(MPa)` or `(-)` and a footnote `*` are ignored):",
        "",
        "| Parameter | Accepted headers |",
        "|---|---|",
    ]
    for key, aliases in SUMMARY_CONSTANTS.items():
        out.append(f"| `{key}` | " + ", ".join(f"`{a}`" for a in aliases) + " |")
    out += [
        "",
        "Any other column whose header is the name of a model parameter in the table below (for",
        "example `k_phi`, `A_OTT`, `vse_mode`) is passed to the models as that parameter.",
        "",
        "## Dataset sheet",
        "",
        "One row per test; columns are found by the tokens their header must contain. Plain",
        "rows (Notched `No`) with a positive cycle count are kept: Run out `No` (or false, 0,",
        "failure) marks a failure, `Yes` (or true, 1, runout) a run-out, whose count is the cycles",
        "completed (a lower bound on life). Run-outs never enter calibration, curve fits or error",
        "statistics; they are evaluated with the same constants, exported with `Flag = 2` and drawn",
        "with arrows in the comparison plots. Other Run out values are dropped with a warning.",
        "Empty or `Null` stress cells are read as 0. Stresses in MPa, phases in degrees with",
        "respect to the axial load.",
        "Radial = sigma_xx, axial = sigma_yy, shear = tau_xy; strains are linear elastic.",
        "",
        "A `Phase AXIAL load` column marks the revised format (October 2026 collection). There the",
        "radial and torsional phases are taken relative to the axial phase, an empty stress cell is",
        "unknown loading (the row is excluded, not read as 0), and a row is also excluded when active",
        "components have different known frequencies (the model is single-harmonic) or when an",
        "internal pressure is given without a radial (hoop) stress. Frequency text such as `15-20`",
        "is kept as text. Forces and moments are never read as stresses; BENDING stress headers are",
        "read as the axial stress. Excluded rows are listed in the validation report.",
        "",
        "| Column | Header tokens | Required |",
        "|---|---|---|",
    ]
    for key, tokens in DATASET_REQUIRED.items():
        out.append(f"| {key} | {tokens_text(tokens)} | yes |")
    for key, tokens in DATASET_OPTIONAL.items():
        out.append(f"| {key} | {tokens_text(tokens)} | no |")
    out += [
        "",
        "Every model is calibrated on the uniaxial tension R = -1 tests (design set), so a",
        "workbook needs at least two of them with distinct lives.",
        "",
        "## Overlays",
        "",
        "A workbook edited after its source supplied it keeps the supplied bytes. Its corrections are",
        "declared in `src/multifat/imp/overlay_files/` and matched to a workbook by its SHA-256, so a copy keeps its corrections; applied in memory when the",
        "file is read: each operation checks the value it replaces, and the overlay applies only to the",
        "file whose SHA-256 it names. `--no-overlay` on `multifat-run`, `multifat-calibrate` and",
        "`multifat-pipeline` gives the workbook as supplied. The applied overlay (name, SHA-256,",
        "number of operations) is recorded in the pipeline provenance and in the validation report.",
        "",
        "## Parameters per model",
        "",
        "Required constants must be in the workbook, or be calibrated by the pipeline (k_FS, k_FI,",
        "L_LI, k_MGSE, a_MSWT from the uniaxial and torsion tests). A model whose required",
        "constants are missing is skipped and reported; the other models still run.",
        "",
        "| Model | Required | Optional (default or fallback) |",
        "|---|---|---|",
    ]
    for name, req, opt in param_table():
        o = "; ".join(f"`{k}`: {v}" for k, v in opt.items()) or "-"
        r = ", ".join(f"`{k}`" for k in req) or "-"
        out.append(f"| {name} | {r} | {o} |")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            raise SystemExit(f"Stale generated file: {OUT.relative_to(ROOT).as_posix()}")
        print("docs/workbook-format.md OK")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT).as_posix())


if __name__ == "__main__":
    main()
